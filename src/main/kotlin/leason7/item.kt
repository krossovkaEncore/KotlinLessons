// package - ключевое слово для создания пакета (команда компилятору)
// lesson7 - имя пакет (как папка или деректория) - группировка файлов и катологов
// Все ниже написаное топерь находится в пакете данных lesson7

// Создание класса предмета
data class Item( // data - ключевое слово: означает "класс данных" (он хранит даннные но не выполняет определеные функции)
    val id: Int, // ( ... ) - в круглых скобках задаются параметры ПЕРВИЧНОГО КОНСТРУКТОРА
    // { ... } - в фигурных скобках ВТОРИЧНЫЙ КОНСТРУКТОР (может не задаваться при объявлении)
    val name: String,
    val description: String,
    val price: Int,
    val weight: Int

) // Закрытие списка параметров конструктора

// {} - скобки не добавляем, потому что класс пока "голый" без доп аргументов внутри